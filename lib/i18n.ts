export function formatCompoundingMode(mode: string) {
  const labels: Record<string, string> = {
    SIMPLE_FIXED_RISK: copy.simulations.simpleFixedRisk,
    COMPOUND: copy.simulations.compound,
    STEP_COMPOUND: copy.simulations.stepCompound,
  };

  return labels[mode] ?? mode;
}

export function formatSamplingMethod(method: string) {
  if (method === "BOOTSTRAP_WITH_REPLACEMENT") {
    return copy.simulations.bootstrap;
  }

  return method;
}
